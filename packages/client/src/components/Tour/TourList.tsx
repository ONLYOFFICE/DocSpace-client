import styles from "./TourTooltip.module.scss";

/**
 * A step body written as a list rather than a paragraph.
 *
 * A step that enumerates several places (the sidebar's shortcuts, a menu's
 * entries) reads badly as prose: the names the user is supposed to find on
 * screen end up buried mid-sentence. Split across bullets, each one starts its
 * own line and the tooltip can be scanned instead of read.
 *
 * Each item is one already-translated, already-interpolated string — the
 * splitting is a layout decision, so the wording stays whatever the locale
 * says it is.
 */
export default function TourList({ items }: { items: string[] }) {
  return (
    <ul className={styles.list}>
      {items.map((item) => (
        <li key={item}>{item}</li>
      ))}
    </ul>
  );
}
